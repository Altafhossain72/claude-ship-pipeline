#!/usr/bin/env python3
"""Deterministic bookkeeping for the /ship orchestrator.

Every run has its own run folder <workspace>/.ship-runs/<slug>/ and its
own git worktree per repo (<repo>-<feature>, next to the repo), so any
number of runs can go in parallel and the user's own checkouts are never
touched. The workspace is the session folder, or the parent of its repo.

  ship.py init <slug>              start a run; prints RUN=<run folder>
  ship.py runs                     list runs in this workspace (active first)
All other commands take the run first:  ship.py --run <RUN> <command>
  join <repo> <branch> [--base <ref>]
                                   create/reuse the worktree for <repo> on
                                   <branch> (new branches start from a fresh
                                   origin/dev, else dev/main/master, never the
                                   user's checkout; no upstream is set);
                                   excludes, constitution, base snapshot
  save <label>                     snapshot every worktree
  changed <label> [--non-docs]     files changed since <label> (abs paths)
  redsum | redcheck                record / verify the RED test checksums
  commitset                        files to commit (changed since base minus
                                   pre-existing edits)
  commit <message>                 commit exactly the commitset per worktree
                                   (never pushes)
  prd-dir                          the workspace (where PRDs live)
  prd-find [<words>...]            PRD files in the workspace (prefix from
                                   ~/.claude/ship.json "prd_prefix", default
                                   "PRD - "), newest first; with words, only
                                   names containing all of them
  prd-save "<Feature>" [--replace|--replace-any]
  prd-text <file.docx>             extract a .docx PRD to <RUN>/prd-source.md
  review-save <prd-file>           save <RUN>/prd-review.md next to the PRD
  end                              finish the run (worktrees are kept)
Exit codes: 0 ok, 1 error, 3 needs a user decision (message on stderr).
"""
import hashlib
import os
import re
import shutil
import subprocess
import sys
from datetime import datetime

P = None  # run folder, set by --run
EMPTY_TREE = "4b825dc642cb6eb9a060e54bf8d69288fbee4904"
PROTECTED = re.compile(r"^(main|master|dev|develop|release/.*|prod.*|stage.*)$")
MARKER = "Generated by /ship analyst"


def prd_prefix():
    """PRD file-name prefix, e.g. "ACME - PRD_" (env SHIP_PRD_PREFIX, else
    "prd_prefix" in ~/.claude/ship.json, else "PRD - ")."""
    import json
    if os.environ.get("SHIP_PRD_PREFIX"):
        return os.environ["SHIP_PRD_PREFIX"]
    try:
        with open(os.path.expanduser("~/.claude/ship.json")) as f:
            return json.load(f).get("prd_prefix") or "PRD - "
    except (OSError, ValueError):
        return "PRD - "
TEMPLATE = """# /ship constitution: {name}
Non-negotiable rules for this repo. Every /ship agent reads this.
Keep it under ~60 lines. Never put customer data, credentials or
hostnames here.

## Rules
- (none yet; add the repo's non-negotiables here)

## Lessons from past runs
"""


def die(msg, code=1):
    print(msg, file=sys.stderr)
    sys.exit(code)


def git(repo, *args, env=None, check=True):
    r = subprocess.run(["git", "-C", repo, *args], capture_output=True, text=True, env=env)
    if check and r.returncode:
        die(f"git {' '.join(args)} in {repo} failed: {r.stderr.strip()}")
    return r.stdout


def norm(path):
    return os.path.realpath(os.path.normpath(os.path.expanduser(path)))


def key(repo):
    return os.path.basename(norm(repo))


def workspace():
    top = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True,
                         text=True).stdout.strip()
    if not top:
        return os.getcwd()
    common = subprocess.run(["git", "rev-parse", "--path-format=absolute", "--git-common-dir"],
                            capture_output=True, text=True).stdout.strip()
    main = os.path.dirname(common) if common.endswith("/.git") else top
    return os.path.dirname(main)


def run_file(*parts):
    return os.path.join(P, *parts)


def lines(path):
    if not os.path.isfile(path):
        return []
    with open(path) as f:
        return [line.rstrip("\n") for line in f if line.strip()]


def repos():
    return [norm(x) for x in lines(run_file("repos.txt"))]


# ---------- snapshots ----------

def tree(repo, label):
    os.makedirs(run_file("snap"), exist_ok=True)
    index = run_file("snap", f"{label}.{key(repo)}.idx")
    if os.path.exists(index):
        os.remove(index)
    real_index = git(repo, "rev-parse", "--path-format=absolute", "--git-path", "index").strip()
    if os.path.exists(real_index):
        shutil.copyfile(real_index, index)
    env = dict(os.environ, GIT_INDEX_FILE=index)
    git(repo, "add", "-A", env=env)
    return git(repo, "write-tree", env=env).strip()


def snap_file(label, repo):
    return run_file("snap", f"{label}.{key(repo)}.tree")


def save(label, only=None):
    for repo in ([norm(only)] if only else repos()):
        value = tree(repo, f"{label}-save")
        with open(snap_file(label, repo), "w") as f:
            f.write(value)


def is_doc(name):
    return bool(re.search(r"(^|/)docs/", name) or re.search(r"(^|/)(README|CHANGELOG)[^/]*$", name))


def changed(label, non_docs=False):
    out = []
    for repo in repos():
        path = snap_file(label, repo)
        if not os.path.isfile(path):
            path = snap_file("base", repo)
        old = open(path).read().strip() if os.path.isfile(path) else EMPTY_TREE
        new = tree(repo, f"{label}-now")
        for name in git(repo, "diff", "--name-only", "-z", old, new).split("\0"):
            if not name or name.startswith((".pipeline/", ".ship/")):
                continue
            if non_docs and is_doc(name):
                continue
            out.append(os.path.join(repo, name))
    return out


def dirty(repo):
    files = []
    entries = git(repo, "status", "--porcelain", "-z", "--untracked-files=all").split("\0")
    i = 0
    while i < len(entries):
        entry = entries[i]
        i += 1
        if not entry:
            continue
        status, name = entry[:2], entry[3:]
        if "R" in status or "C" in status:
            i += 1
        if not name.startswith((".pipeline/", ".ship/")):
            files.append(os.path.join(repo, name))
    return files


# ---------- run lifecycle ----------

def cmd_init(slug):
    if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)+", slug):
        die("run slug must be the feature part of the branch, e.g. adm-0049-transaction-limit-usage")
    run = os.path.join(workspace(), ".ship-runs", slug)
    if os.path.isfile(os.path.join(run, ".active")):
        die(f"a run for '{slug}' is already active ({run}); resume it with --run, "
            "or ask the user", 3)
    shutil.rmtree(run, ignore_errors=True)
    os.makedirs(run)
    for name in (".active", "pre-run.txt"):
        open(os.path.join(run, name), "w").close()
    print(f"RUN={run}")


def cmd_runs():
    base = os.path.join(workspace(), ".ship-runs")
    if not os.path.isdir(base):
        print("no runs")
        return
    for name in sorted(os.listdir(base), key=lambda n: not os.path.isfile(os.path.join(base, n, ".active"))):
        run = os.path.join(base, name)
        state = "active" if os.path.isfile(os.path.join(run, ".active")) else "ended"
        trees = ", ".join(lines(os.path.join(run, "repos.txt"))) or "(no repos yet)"
        print(f"{state:6} {name}  {trees}")


def main_repo(path):
    common = git(path, "rev-parse", "--path-format=absolute", "--git-common-dir").strip()
    return os.path.dirname(common) if common.endswith("/.git") else git(path, "rev-parse", "--show-toplevel").strip()


def worktree_for(main, branch):
    current = None
    for line in git(main, "worktree", "list", "--porcelain").splitlines():
        if line.startswith("worktree "):
            current = line[9:]
        elif line == f"branch refs/heads/{branch}":
            return current
    return None


def default_base(main):
    fetched = subprocess.run(["git", "-C", main, "fetch", "--quiet", "origin"],
                             capture_output=True, text=True)
    note = "" if fetched.returncode == 0 else " (fetch failed, using the local copy)"
    for ref in ("origin/dev", "dev", "origin/develop", "develop", "origin/main", "main",
                "origin/master", "master"):
        if git(main, "rev-parse", "--verify", "--quiet", ref, check=False).strip():
            return ref, note
    return "HEAD", " (no dev/main branch found)"


def cmd_join(repo, branch, base=None):
    main = main_repo(norm(repo))
    if not re.match(r"^(feat|fix)/[a-z0-9]+(-[a-z0-9]+)+$", branch) or \
            re.fullmatch(r"(feat|fix)/[a-z]+-\d+", branch):
        die(f"branch name '{branch}' must be <feat|fix>/[<ticket>-]<2-5 words>, e.g. "
            "feat/adm-0049-transaction-limit-usage or fix/beneficiary-empty-nickname")
    slug = branch.split("/", 1)[1]
    wt = worktree_for(main, branch)
    if wt:
        note = f"reusing existing worktree {wt}"
    else:
        wt = os.path.join(os.path.dirname(main), f"{os.path.basename(main)}-{slug}")
        if os.path.exists(wt):
            die(f"{wt} exists but is not a worktree of {branch}; ask the user", 3)
        exists = git(main, "rev-parse", "--verify", "--quiet", f"refs/heads/{branch}", check=False).strip()
        if exists:
            git(main, "worktree", "add", wt, branch)
            note = f"created worktree {wt} on existing branch {branch}"
        else:
            fetch_note = ""
            if not base:
                base, fetch_note = default_base(main)
            git(main, "worktree", "add", "--no-track", "-b", branch, wt, base)
            short = git(main, "rev-parse", "--short", base).strip()
            note = f"created worktree {wt} on new branch {branch} from {base} @ {short}{fetch_note}"
    wt = norm(wt)
    if wt in repos():
        print(f"{wt} already in the run")
        return
    exclude = git(main, "rev-parse", "--path-format=absolute", "--git-common-dir").strip() + "/info/exclude"
    os.makedirs(os.path.dirname(exclude), exist_ok=True)
    text = open(exclude).read() if os.path.isfile(exclude) else ""
    missing = [e for e in (".pipeline/", ".ship/", "target/", "build/", ".gradle/")
               if e not in text.splitlines()]
    if missing:
        with open(exclude, "a") as f:
            if text and not text.endswith("\n"):
                f.write("\n")
            f.writelines(e + "\n" for e in missing)
    constitution = os.path.join(main, ".ship", "constitution.md")
    created = not os.path.isfile(constitution)
    if created:
        os.makedirs(os.path.dirname(constitution), exist_ok=True)
        with open(constitution, "w") as f:
            f.write(TEMPLATE.format(name=os.path.basename(main)))
    with open(run_file("repos.txt"), "a") as f:
        f.write(wt + "\n")
    with open(run_file("constitutions.txt"), "a") as f:
        f.write(constitution + "\n")
    with open(run_file("mains.txt"), "a") as f:
        f.write(f"{wt}\t{main}\n")
    pre = dirty(wt)
    with open(run_file("pre-run.txt"), "a") as f:
        f.writelines(x + "\n" for x in pre)
    save("base", only=wt)
    head = git(wt, "log", "-1", "--format=%h %s").strip()
    print(f"joined {os.path.basename(main)}: {note} (HEAD {head})")
    print(f"  agents work in {wt}; the user's checkout {main} is untouched")
    if created:
        print(f"  created empty constitution {constitution}")
    if pre:
        print(f"  {len(pre)} uncommitted file(s) already in that worktree, never committed:")
        for x in pre[:20]:
            print(f"    {x}")


def red_files():
    path = run_file("red-tests.txt")
    if not os.path.isfile(path):
        die("no red-tests.txt in the run folder")
    return lines(path)


def digest(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def cmd_redsum():
    with open(run_file("red.sha"), "w") as f:
        for path in red_files():
            f.write(f"{digest(path)}  {path}\n")
    print("RED checksums recorded")


def cmd_redcheck():
    bad = []
    for line in lines(run_file("red.sha")):
        want, path = line.split("  ", 1)
        if not os.path.isfile(path) or digest(path) != want:
            bad.append(path)
    if bad:
        die("RED tests changed after RED:\n" + "\n".join(bad), 3)
    print("RED tests intact")


def commitset():
    user = set(lines(run_file("pre-run.txt")))
    files = changed("base")
    return [x for x in files if x not in user], [x for x in files if x in user]


def cmd_commitset():
    files, overlap = commitset()
    for x in files:
        print(x)
    if overlap:
        print("ALSO CHANGED, BUT HELD EARLIER UNCOMMITTED EDITS (not committed, ask the user):",
              file=sys.stderr)
        for x in overlap:
            print(f"  {x}", file=sys.stderr)
        sys.exit(3)


def cmd_commit(message):
    files, overlap = commitset()
    if overlap:
        die("files with earlier uncommitted edits changed; run commitset and ask the user", 3)
    by_repo = {}
    for x in files:
        repo = next(r for r in repos() if x.startswith(r + "/"))
        by_repo.setdefault(repo, []).append(os.path.relpath(x, repo))
    if not by_repo:
        die("nothing to commit")
    for repo, names in by_repo.items():
        current = git(repo, "branch", "--show-current").strip()
        if not current or PROTECTED.match(current):
            die(f"{repo} is on protected branch '{current}'; not committing")
        git(repo, "add", "-A", "--", *names)
        git(repo, "commit", "-m", message, "--", *names)
        print(f"{repo} {current} {git(repo, 'rev-parse', '--short', 'HEAD').strip()} ({len(names)} files)")


# ---------- PRD ----------

def prd_version(text):
    m = re.search(r"(?:\bv|Version\W{0,6})(\d+(?:\.\d+)*)\b", text[:3000], re.I)
    return m.group(1) if m else None


def cmd_prd_text(path):
    import zipfile
    from xml.etree import ElementTree
    ns = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
    with zipfile.ZipFile(path) as z:
        root = ElementTree.fromstring(z.read("word/document.xml"))
    text = ["".join(t.text or "" for t in para.iter(f"{ns}t")) for para in root.iter(f"{ns}p")]
    dest = run_file("prd-source.md")
    with open(dest, "w") as f:
        f.write(f"<!-- text extracted from {path} -->\n" + "\n".join(text) + "\n")
    print(f"PRD text: {dest}")


def cmd_prd_save(title, replace):
    src = run_file("prd.md")
    if not os.path.isfile(src):
        die("no prd.md in the run folder")
    if re.search(r"[/\\]", title):
        die("feature name must not contain slashes")
    dest = os.path.join(workspace(), f"{prd_prefix()} {title}.md".replace("  ", " "))
    if os.path.isfile(dest):
        old = open(dest, errors="replace").read()
        if not replace:
            die(f"{dest} already exists; pick another name, or pass --replace if the user "
                "explicitly asked to replace it", 3)
        if MARKER not in old[:3000] and replace != "--replace-any":
            die(f"{dest} was not written by /ship (likely authored by the client); it is never "
                "replaced unless the user explicitly names it (--replace-any)", 3)
        stamp = prd_version(old) or datetime.now().strftime("%Y%m%d%H%M")
        backup = dest[:-3] + f".v{stamp}.bak.md"
        n = 1
        while os.path.exists(backup):
            n += 1
            backup = dest[:-3] + f".v{stamp}-{n}.bak.md"
        shutil.copyfile(dest, backup)
        print(f"previous version kept as {backup}")
    shutil.copyfile(src, dest)
    print(f"PRD saved: {dest}")


def cmd_review_save(prd):
    src = run_file("prd-review.md")
    if not os.path.isfile(src) or not os.path.isfile(prd):
        die("need prd-review.md in the run folder and an existing PRD file")
    stem, ext = os.path.splitext(os.path.basename(prd))
    stem = stem[len(prd_prefix()):].strip() if stem.startswith(prd_prefix()) else stem
    text_src = prd if ext == ".md" else run_file("prd-source.md")
    ver = prd_version(open(text_src, errors="replace").read()) if os.path.isfile(text_src) else None
    folder = os.path.dirname(os.path.abspath(prd))
    base = f"{stem}-PRD{'-v' + ver if ver else ''}-VALIDATION-{datetime.now():%Y-%m-%d}"
    dest = os.path.join(folder, base + ".md")
    n = 1
    while os.path.exists(dest):
        n += 1
        dest = os.path.join(folder, f"{base}-{n}.md")
    shutil.copyfile(src, dest)
    print(f"PRD review saved: {dest}")


def main(argv):
    global P
    if argv[:1] == ["--run"]:
        if len(argv) < 3:
            die(__doc__)
        P = norm(argv[1])
        if not os.path.isdir(P):
            die(f"run folder {P} does not exist")
        argv = argv[2:]
    if not argv:
        die(__doc__)
    cmd, args = argv[0], argv[1:]
    if cmd == "init" and len(args) == 1:
        return cmd_init(args[0])
    if cmd == "runs":
        return cmd_runs()
    if cmd == "prd-dir":
        return print(workspace())
    if cmd == "prd-find":
        ws, pre = workspace(), prd_prefix()
        hits = [f for f in os.listdir(ws) if f.startswith(pre) and ".bak" not in f
                and os.path.splitext(f)[1].lower() in (".md", ".docx", ".pdf")
                and all(w.lower() in f.lower() for w in args)]
        hits.sort(key=lambda f: -os.path.getmtime(os.path.join(ws, f)))
        for f in hits:
            print(os.path.join(ws, f))
        return None
    if P is None:
        die(f"'{cmd}' needs --run <RUN> first")
    if cmd == "join" and len(args) in (2, 4) and (len(args) == 2 or args[2] == "--base"):
        cmd_join(args[0], args[1], args[3] if len(args) == 4 else None)
    elif cmd == "save" and len(args) == 1:
        save(args[0])
    elif cmd == "changed" and args:
        print("\n".join(changed(args[0], "--non-docs" in args)))
    elif cmd == "redsum":
        cmd_redsum()
    elif cmd == "redcheck":
        cmd_redcheck()
    elif cmd == "commitset":
        cmd_commitset()
    elif cmd == "commit" and args:
        cmd_commit(" ".join(args))
    elif cmd == "prd-save" and args:
        flags = [a for a in args if a.startswith("--replace")]
        cmd_prd_save(" ".join(a for a in args if not a.startswith("--replace")),
                     flags[0] if flags else None)
    elif cmd == "prd-text" and len(args) == 1:
        cmd_prd_text(args[0])
    elif cmd == "review-save" and len(args) == 1:
        cmd_review_save(args[0])
    elif cmd == "end":
        path = run_file(".active")
        if os.path.exists(path):
            os.remove(path)
        print("run ended; worktrees kept for review:")
        for wt in repos():
            print(f"  {wt}")
    else:
        die(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
